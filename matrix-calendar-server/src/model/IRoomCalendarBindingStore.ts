import { RoomCalendarBinding } from './IRoomCalendarBinding';

/**
 * Maximum total bindings accepted across immutable static config and dynamic
 * store rows. Pending dynamic reservations consume capacity.
 */
export const ROOM_CALENDAR_BINDING_LIMITS = Object.freeze({
  maxConfiguredBindings: 32,
});

export type RoomCalendarBindingRecordStatus = 'pending' | 'ready';

/** Persistent lifecycle data; never contains calendar event content or secrets. */
export type RoomCalendarBindingRecord = RoomCalendarBinding &
  Readonly<{
    status: RoomCalendarBindingRecordStatus;
    createdBy: string;
    createdAt: Date;
    readyAt?: Date;
  }>;

export type RoomCalendarBindingReservation = Readonly<{
  /** Candidate ID generated by the server, never supplied by a Matrix client. */
  binding: RoomCalendarBinding;
  /** Validated immutable configuration used to reject static collisions. */
  staticBindings: readonly RoomCalendarBinding[];
  /** Current authenticated Matrix room-event sender. */
  createdBy: string;
  createdAt: Date;
}>;

export type RoomCalendarBindingReservationResult =
  | Readonly<{ kind: 'reserved'; record: RoomCalendarBindingRecord }>
  | Readonly<{ kind: 'existing'; record: RoomCalendarBindingRecord }>
  | Readonly<{ kind: 'static-conflict' }>
  | Readonly<{ kind: 'collection-conflict' }>
  | Readonly<{ kind: 'capacity-reached' }>;

/**
 * Durable, append-only room binding persistence. There is deliberately no
 * update, rebind, or delete method. Implementations serialize reservations
 * transactionally and enforce unique room and calendar IDs in PostgreSQL.
 */
export interface RoomCalendarBindingStore {
  readonly enabled: boolean;

  /** Return every dynamic row, including pending rows, without truncation. */
  listAll(): Promise<readonly RoomCalendarBindingRecord[]>;

  /**
   * Atomically return the room's existing reservation or insert a new pending
   * row. Enforce static collisions, unique room/calendar IDs, and the total
   * static-plus-dynamic cap (counting pending and ready rows) in the same
   * transaction. Same-room retries retain the stored ID.
   */
  reserve(
    reservation: RoomCalendarBindingReservation,
  ): Promise<RoomCalendarBindingReservationResult>;

  /** Transition the exact pending row to ready; an exact ready row is a no-op. */
  markReady(
    binding: RoomCalendarBinding,
    readyAt: Date,
  ): Promise<RoomCalendarBindingRecord>;
}
